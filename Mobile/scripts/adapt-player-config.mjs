// Reproduce standalone wearable/kit codecs and body palettes from pinned BSD TSPS.
import {readFile,writeFile} from "node:fs/promises";
import {stripTypeScriptTypes} from "node:module";
const upstream=new URL("../tsps-upstream/",import.meta.url);
const license=await readFile(new URL("LICENSE",upstream),"utf8");
const header="/*\n"+license.trim()+"\n*/\n// Generated by scripts/adapt-player-config.mjs from pinned TSPS b9ca431.\n";
let kit=await readFile(new URL("client/rs/config/idktype/IdkType.ts",upstream),"utf8");
kit=kit.replace(/^import .*;\r?\n/gm,"");
// Unknown kit opcodes cannot be silently ignored by the standalone decoder.
kit=kit.replace(/(this\.ifModelIds\[opcode - 70\] = buffer\.readInt\(\);\s*)}/,"$1} else { throw new Error('Unsupported identity kit opcode '+opcode); }");
let item=await readFile(new URL("client/rs/config/objtype/ObjType.ts",upstream),"utf8");
item=item.slice(item.indexOf("export class ObjType"),item.indexOf("    override post(): void"))+"}\n";
const base=`import {ByteBuffer} from './cache-reader.mjs';
const ObjStackability={SOMETIMES:0,ALWAYS:1,NEVER:2};
class Type {
    constructor(id){this.id=id;this.cacheInfo={game:'oldschool',revision:240};this.cacheType='dat2';}
    readString(buffer){return buffer.readString();}
    static readParamsMap(b,params=new Map()){
        for(let n=b.readUnsignedByte();n>0;n--){const string=b.readUnsignedByte(),key=b.readMedium();params.set(key,string?b.readString():b.readInt());}return params;
    }
    decode(bytes){
        const b=new ByteBuffer(bytes);
        for(let n=0;n<4096;n++){const op=b.readUnsignedByte();if(!op){if(b.offset!==b.length)throw new Error('Trailing player config data');return this;}this.decodeOpcode(op,b);}
        throw new Error('Player config opcode limit exceeded');
    }
}
`;
await writeFile(new URL("../browser/player-config.mjs",import.meta.url),header+stripTypeScriptTypes(base+kit+item,{mode:"strip"}));
const colors=await readFile(new URL("client/rs/config/player/PlayerDesignColors.ts",upstream),"utf8");
await writeFile(new URL("../browser/player-colors.mjs",import.meta.url),header+stripTypeScriptTypes(colors,{mode:"strip"}));
await writeFile(new URL("../licenses/rsprox-MIT.txt",import.meta.url),await readFile(new URL("../../Client/LICENSE",import.meta.url),"utf8"));
