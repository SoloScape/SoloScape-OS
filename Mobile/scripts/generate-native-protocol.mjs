// Regenerate only the revision-240 desktop server packet framing table and licence.
// No upstream runtime dependency, game cache data or credentials.
import {writeFile,mkdir} from "node:fs/promises";
const ref="5144f569d41a7c2cf77f2b44a8d6e5bca41366d0";
const root=`https://raw.githubusercontent.com/blurite/rsprot/${ref}/`;
const directory="protocol/osrs-240/osrs-240-desktop/src/main/kotlin/net/rsprot/protocol/game/outgoing/prot/";
async function source(path){const response=await fetch(root+path);if(!response.ok)throw new Error("rsprot source unavailable");return response.text();}
const [idsSource,tableSource,license]=await Promise.all([source(directory+"GameServerProtId.kt"),source(directory+"GameServerProt.kt"),source("LICENSE")]);
const ids=new Map([...idsSource.matchAll(/const val (\w+) = (\d+)/g)].map(m=>[m[1],Number(m[2])]));
const entries=[...tableSource.matchAll(/^\s*(\w+)\(GameServerProtId\.(\w+), ([\w.-]+)\)/gm)].map(m=>{
    const size=m[3]==="Prot.VAR_BYTE"?-1:m[3]==="Prot.VAR_SHORT"?-2:Number(m[3]);
    if(m[1]!==m[2]||!ids.has(m[2])||!Number.isInteger(size))throw new Error("Unsupported packet table entry");
    return {opcode:ids.get(m[2]),size,name:m[1]};
}).sort((a,b)=>a.opcode-b.opcode);
// The source reserves UNHANDLED without a known payload size; fail closed on that opcode.
ids.delete("UNHANDLED");
if(entries.length!==ids.size||new Set(entries.map(e=>e.opcode)).size!==entries.length)throw new Error("Incomplete packet table");
const lines=entries.map(e=>`    [${e.opcode},{name:"${e.name}",size:${e.size}}],`).join("\n");
await mkdir(new URL("../licenses/",import.meta.url),{recursive:true});
await writeFile(new URL("../licenses/rsprot-MIT.txt",import.meta.url),license);
await writeFile(new URL("../browser/game-protocol.mjs",import.meta.url),
    `// Generated by scripts/generate-native-protocol.mjs from rsprot ${ref}.\n`+
    `// Revision 240 desktop, 1.0.0-ALPHA-20260912. See ../licenses/rsprot-MIT.txt.\n`+
    `export const SERVER_PACKETS=new Map([\n${lines}\n]);\n`+
    `export const CLIENT_NO_TIMEOUT=99;\n`);
console.log(`Generated ${entries.length} revision-240 server packet entries`);
