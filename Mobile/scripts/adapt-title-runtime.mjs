// Reproduce TSPS's title fire and complete cache MIDI/sample synthesizer.
import {readFile,writeFile} from "node:fs/promises";
import {stripTypeScriptTypes} from "node:module";
import {dirname,resolve,basename} from "node:path";
import {fileURLToPath} from "node:url";
const upstream=fileURLToPath(new URL("../tsps-upstream/client/",import.meta.url));
const output=new URL("../browser/",import.meta.url);
const license=await readFile(new URL("../tsps-upstream/LICENSE",import.meta.url),"utf8");
const header="/*\n"+license.trim()+"\n*/\n// Generated by scripts/adapt-title-runtime.mjs from pinned TSPS b9ca431.\n";
const names=new Map(),seen=new Set();
const clean=source=>source.replace(/[\t ]+$/gm,"");
const name=path=>"title-audio-"+basename(path,".ts").replace(/([a-z0-9])([A-Z])/g,"$1-$2").toLowerCase()+".mjs";
async function adapt(path){
    if(seen.has(path))return names.get(path);seen.add(path);
    const target=name(path);names.set(path,target);
    let source=await readFile(path,"utf8");
    const imports=[...source.matchAll(/^import[\s\S]*?from\s+"([^"]+)";\r?\n/gm)];
    for(const match of imports){
        const spec=match[1];let replacement;
        if(spec.endsWith("CacheSystem"))replacement="";
        else if(spec.endsWith("IndexType"))replacement='import {IndexType} from "./title-audio-cache.mjs";\n';
        else if(spec.endsWith("retryOnMissingGroup"))replacement='import {retryOnMissingGroup} from "./title-audio-cache.mjs";\n';
        else if(spec.endsWith("VorbisWasm"))replacement='import {loadVorbisSample} from "./title-audio-vorbis.mjs";\n';
        else{
            const dependency=resolve(dirname(path),spec+".ts");
            const dependencyName=await adapt(dependency);
            replacement=match[0].replace(spec,"./"+dependencyName).replace(/,\s*VorbisFloorState/g,"");
        }
        source=source.replace(match[0],replacement);
    }
    if(path.endsWith("RealtimeMidiSynth.ts")){
        const needle="const patch = MusicPatch.tryLoad(this.cache, patchId);";
        if(!source.includes(needle))throw new Error("Pinned music patch seam changed");
        source=source.replace(needle,"await this.cache.preload(15, patchId);\n        "+needle);
        const worklet=source.match(/private getWorkletProcessorCode\(\): string \{[\s\S]*?return `([\s\S]*?)`;\s*}/);
        if(!worklet||worklet[1].includes("${"))throw new Error("Pinned worklet seam changed");
        await writeFile(new URL("title-music-worklet.mjs",output),clean(header+worklet[1]));
    }
    if(path.endsWith("audioContext.ts")){
        const block=/const code = await getWorkletCode\(\);[\s\S]*?URL\.revokeObjectURL\(url\);\s*}/;
        if(!block.test(source))throw new Error("Pinned worklet registration seam changed");
        source=source.replace(block,'await ctx.audioWorklet.addModule(new URL("./title-music-worklet.mjs",import.meta.url).href);');
    }
    await writeFile(new URL(target,output),clean(header+stripTypeScriptTypes(source,{mode:"transform"})));
    return target;
}
await adapt(resolve(upstream,"game/audio/music/realtime/RealtimeMidiSynth.ts"));
await adapt(resolve(upstream,"rs/audio/vorbis/VorbisSample.ts"));
let fire=await readFile(resolve(upstream,"game/login/LoginScreenAnimation.ts"),"utf8");
fire=fire.replace(/^import.*;\r?\n/gm,"");
await writeFile(new URL("title-fire.mjs",output),clean(header+stripTypeScriptTypes(fire,{mode:"transform"})));
console.log("Adapted TSPS title fire and "+seen.size+" music modules");
